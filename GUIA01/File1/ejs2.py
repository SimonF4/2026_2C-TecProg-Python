# Consigna:
#       2. Suma simple: Ingresar dos números y mostrar el resultado.

# Ingreso de los valores.
#   Se puede usar de castear a float o a int.
num1 = float( input("Ingrese el 1er numero:") )
num2 = float( input("Ingrese el 2do numero:") )

# Proceso
suma = num1 + num2

# Mostrar resultado
print(f"El resultado de la suma de {num1} y {num2} es de: ", suma )
