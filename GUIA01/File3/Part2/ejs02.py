# Ejercicio 2: Encontrar el mayor de dos números (recomendado)⭐

# En Python:
# Ingreso de los valores.
#   Se puede usar de castear a float o a int.
num1 = float(input("Ingrese el 1er numero:"))
num2 = float(input("Ingrese el 2do numero:"))


# Proceso
if (num1 == num2):
    print("Son iguales")
elif (num1 > num2):
    print("Es mayor el 1er número")
else:
    print("Es mayor el 2do número")
